-- 8b. WeatherSource POINT_FORECAST_DAY sample (Calgary, 15 days ahead)
CREATE OR REPLACE TABLE AVEVA_WORLD_DEMOS.STREAMLIT_APPS.WEATHER_FORECAST_SAMPLE AS
WITH forecast_days AS (
    SELECT DATEADD('day', SEQ4() + 1, CURRENT_DATE()) AS dt
    FROM TABLE(GENERATOR(ROWCOUNT => 15))
),
init_times AS (
    SELECT column1 AS init_offset_hrs FROM VALUES (0), (6), (12)
),
monthly_params AS (
    SELECT column1 AS mo, column2 AS avg_f, column3 AS min_delta, column4 AS max_delta,
           column5 AS wind, column6 AS humid
    FROM VALUES
        (1,  27.4, -8.7, 8.9,  8.0, 61.5),
        (2,  26.9, -9.4, 8.9,  7.6, 58.8),
        (3,  30.3, -9.8, 10.7, 8.3, 67.0),
        (4,  39.9, -10.2, 9.3, 8.5, 62.6),
        (5,  55.8, -12.4, 11.3, 7.5, 52.4),
        (6,  60.8, -11.1, 10.2, 7.3, 52.8),
        (7,  62.7, -9.6, 8.8,  7.0, 68.6),
        (8,  65.2, -11.7, 11.3, 5.7, 62.5),
        (9,  62.0, -12.3, 12.4, 5.8, 55.5),
        (10, 44.7, -9.9, 10.4, 7.5, 52.1),
        (11, 32.7, -8.3, 8.7,  5.6, 69.3),
        (12, 18.2, -10.1, 12.0, 7.1, 72.5)
)
SELECT
    'calgary' AS CITY_NAME,
    'CA' AS COUNTRY_CODE,
    51.0447 AS LATITUDE_DEG,
    -114.0719 AS LONGITUDE_DEG,
    DATEADD('hour', i.init_offset_hrs, d.dt::TIMESTAMP_NTZ) AS TIME_INIT_UTC,
    d.dt AS DATE_VALID_STD,
    DAYOFYEAR(d.dt) AS DOY_STD,
    ROUND(p.avg_f + p.min_delta + UNIFORM(-3.0, 3.0, RANDOM()), 1) AS MIN_TEMPERATURE_AIR_2M_F,
    ROUND(p.avg_f + UNIFORM(-4.0, 4.0, RANDOM()), 1) AS AVG_TEMPERATURE_AIR_2M_F,
    ROUND(p.avg_f + p.max_delta + UNIFORM(-3.0, 3.0, RANDOM()), 1) AS MAX_TEMPERATURE_AIR_2M_F,
    ROUND(p.wind + UNIFORM(-2.0, 3.0, RANDOM()), 1) AS "__AVG_WIND_SPEED_10M_MPH",
    ROUND(p.wind + UNIFORM(2.0, 8.0, RANDOM()), 1) AS "__MAX_WIND_SPEED_10M_MPH",
    ROUND(GREATEST(0, UNIFORM(-0.02, 0.15, RANDOM())), 2) AS TOT_PRECIPITATION_IN,
    ROUND(UNIFORM(5, 60, RANDOM()), 0) AS PROBABILITY_OF_PRECIPITATION_PCT,
    ROUND(CASE WHEN MONTH(d.dt) IN (11,12,1,2,3,4) THEN UNIFORM(0, 40, RANDOM()) ELSE 0 END, 0) AS PROBABILITY_OF_SNOW_PCT
FROM forecast_days d
CROSS JOIN init_times i
JOIN monthly_params p ON p.mo = MONTH(d.dt)
ORDER BY d.dt, i.init_offset_hrs;

-- 8c. Yes Energy DART_PRICES_SAMPLE (hourly, Jan 2024 - Jan 2026)
CREATE OR REPLACE TABLE AVEVA_WORLD_DEMOS.STREAMLIT_APPS.DART_PRICES_SAMPLE AS
WITH hourly_series AS (
    SELECT DATEADD('hour', SEQ4(), '2024-01-27 00:00:00'::TIMESTAMP_NTZ) AS dt
    FROM TABLE(GENERATOR(ROWCOUNT => 17617))
),
monthly_avg AS (
    -- Monthly DALMP averages from real ERCOT data
    SELECT column1 AS yr, column2 AS mo, column3 AS avg_da, column4 AS avg_rt
    FROM VALUES
        (2024, 1, 21.5, 18.8), (2024, 2, 14.4, 14.0), (2024, 3, 18.0, 16.8),
        (2024, 4, 21.6, 23.4), (2024, 5, 42.7, 35.1), (2024, 6, 28.6, 27.3),
        (2024, 7, 22.5, 22.3), (2024, 8, 34.8, 34.3), (2024, 9, 22.6, 23.7),
        (2024, 10, 25.3, 23.1), (2024, 11, 23.3, 31.2), (2024, 12, 25.1, 25.2),
        (2025, 1, 31.1, 32.9), (2025, 2, 33.8, 33.5), (2025, 3, 29.4, 26.6),
        (2025, 4, 32.1, 32.1), (2025, 5, 35.0, 35.2), (2025, 6, 31.3, 28.6),
        (2025, 7, 36.2, 33.5), (2025, 8, 38.5, 34.0), (2025, 9, 30.3, 30.3),
        (2025, 10, 30.5, 30.5), (2025, 11, 33.5, 32.0), (2025, 12, 33.5, 35.0),
        (2026, 1, 81.3, 51.0)
)
SELECT
    10000697078 AS OBJECTID,
    h.dt AS DATETIME,
    'CDT' AS TIMEZONE,
    ROUND(GREATEST(0, m.avg_da + UNIFORM(-15.0, 25.0, RANDOM()) +
        CASE WHEN HOUR(h.dt) BETWEEN 14 AND 19 THEN UNIFORM(5.0, 30.0, RANDOM()) ELSE 0 END), 2) AS DALMP,
    NULL AS DACONG,
    NULL AS DALOSS,
    ROUND(GREATEST(0, m.avg_rt + UNIFORM(-15.0, 20.0, RANDOM()) +
        CASE WHEN HOUR(h.dt) BETWEEN 14 AND 19 THEN UNIFORM(3.0, 25.0, RANDOM()) ELSE 0 END), 2) AS RTLMP,
    NULL AS RTCONG,
    NULL AS RTLOSS,
    'Y' AS RTFINAL,
    ABS(HASH(h.dt)) AS LOADID,
    NULL AS HALMP,
    NULL AS HACONG,
    NULL AS HALOSS,
    'E' AS ISO,
    NULL AS PROXYCODE
FROM hourly_series h
LEFT JOIN monthly_avg m ON m.yr = YEAR(h.dt) AND m.mo = MONTH(h.dt)
ORDER BY h.dt;

