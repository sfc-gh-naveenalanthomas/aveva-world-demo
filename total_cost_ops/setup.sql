-- =============================================================================
-- AVEVA World 2026 - Total Cost of Operations Demo
-- Full Setup Script
-- =============================================================================
--
-- This script creates all internal data objects needed to run the
-- Total Cost of Operations demo on a new Snowflake account.
--
-- PREREQUISITES (external data — cannot be replicated by this script):
--
--   1. AVEVA Catalog-Linked Database
--      Database: CONNECT_AWC26  (or AVEVA_CLD_DATA on some accounts)
--      Schema:   "f6dd054e-d7b7-4b48-97f3-1b0eb2e91ab0"
--      Tables:   mining_haul_truck_narrow_26q1  (truck telemetry, 1.7M+ rows)
--                water_leakage_pump_narrow_live  (pump SCADA, 7.4M+ rows)
--      Setup:    Attach the AVEVA CLD via Snowflake Catalog Integration.
--      NOTE:     If your CLD database is named differently, search-replace
--               CONNECT_AWC26 with your database name in this script.
--
--   2. WeatherSource (Snowflake Marketplace)
--      Database: GLOBAL_WEATHER__CLIMATE_DATA_FOR_BI
--      Schema:   PWS_BI_SAMPLE
--      Tables:   POINT_HISTORY_DAY, POINT_FORECAST_DAY
--      Setup:    Install 'Global Weather & Climate Data for BI' from the
--               Snowflake Marketplace (provider: WeatherSource).
--
--   3. Yes Energy (Snowflake Marketplace)
--      Database: YES_ENERGY__SAMPLE_DATA
--      Schema:   YES_ENERGY_SAMPLE
--      Table:    DART_PRICES_SAMPLE
--      Setup:    Install 'Yes Energy Sample Data' from the
--               Snowflake Marketplace (provider: Yes Energy).
--
--   4. Cortex AI enabled on the account (mistral-large2 model)
--
--   5. ACCOUNTADMIN or a role with CREATE DATABASE, CREATE WAREHOUSE privileges
--
-- Usage:
--   1. Ensure all 3 Marketplace listings above are installed
--   2. Update the AVEVA CLD schema ID if yours differs
--   3. Run this script in a Snowflake worksheet or via SnowSQL
--   4. Deploy the Streamlit app with:
--        snow streamlit deploy --replace --connection <your_connection>
--
-- =============================================================================

